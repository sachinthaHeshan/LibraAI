import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";

import { AI_DISCLOSURE } from "@/lib/chat";

import { AiDisclosure, ChatProvenance } from "./ChatProvenance";

describe("ChatProvenance", () => {
  it("renders nothing without metadata", () => {
    expect(renderToStaticMarkup(<ChatProvenance />)).toBe("");
  });

  it("labels the reply as AI-generated with the agents and tools used", () => {
    const html = renderToStaticMarkup(
      <ChatProvenance
        meta={{ agents: ["searchAgent"], tools: ["searchBooks", "getBook"], refusal: null, piiRedactions: 0 }}
      />,
    );
    expect(html).toContain("AI-generated by Catalog search: searched the catalog, checked availability");
    expect(html).not.toContain("hidden from the AI");
  });

  it("explains refusals and masked personal details", () => {
    const html = renderToStaticMarkup(
      <ChatProvenance
        meta={{ agents: [], tools: [], refusal: "bulk_pii_export", piiRedactions: 1 }}
      />,
    );
    expect(html).toContain("Declined by LibraAI&#x27;s safety policy (exporting personal data)");
    expect(html).toContain("hidden from the AI");
  });
});

describe("AiDisclosure", () => {
  it("shows the standing AI notice", () => {
    expect(renderToStaticMarkup(<AiDisclosure />)).toContain(AI_DISCLOSURE);
  });
});
